from datetime import datetime, timezone

from pydantic import BaseModel, ConfigDict, Field, field_serializer

from app.schemas.product import ProductRead
from app.schemas.stock import BatchCut, CutPiece, CutRead, MaterialRead, PlannedCut, UserBrief


# --- What the worker asks for ---
class AssemblyPieceLine(BaseModel):
    """Several identical pieces of one length."""
    length_mm: int = Field(..., gt=0, le=100000)
    quantity: int = Field(1, ge=1, le=200)
    # True: the pieces go into the assembly; False: they go back to stock
    used: bool = True


class AssemblyMaterialLine(BaseModel):
    material_id: int
    pieces: list[AssemblyPieceLine] = Field(..., min_length=1, max_length=50)


class AssemblyProductLine(BaseModel):
    product_id: int
    quantity: int = Field(..., ge=1, le=100000)


class AssemblyPlanRequest(BaseModel):
    materials: list[AssemblyMaterialLine] = Field(default_factory=list, max_length=50)
    products: list[AssemblyProductLine] = Field(default_factory=list, max_length=100)


# --- The preview ---
class PlannedMaterial(BaseModel):
    material: MaterialRead
    # Which stock item each piece is cut from, fullest first
    cuts: list[PlannedCut]
    # Pieces that fit into no free stock item
    unplaced: list[CutPiece]
    longest_available_mm: int | None = None


class PlannedProduct(BaseModel):
    product: ProductRead
    quantity: int
    available: int


class AssemblyPlan(BaseModel):
    materials: list[PlannedMaterial]
    products: list[PlannedProduct]
    # Everything fits and every product is in stock
    ok: bool


# --- Finishing ---
class AssemblyCreate(BaseModel):
    # Generated by the browser for the draft; the same key is never saved twice
    client_key: str = Field(..., min_length=8, max_length=64)
    name: str | None = Field(None, max_length=150)
    note: str | None = Field(None, max_length=500)
    # The cuts of the plan the worker confirmed
    cuts: list[BatchCut] = Field(default_factory=list, max_length=50)
    products: list[AssemblyProductLine] = Field(default_factory=list, max_length=100)


class AssemblyGoods(BaseModel):
    """Piece goods taken out of stock for the assembly."""
    product: ProductRead
    # Number of pieces taken: the movement stores it as a negative change
    quantity: int
    model_config = ConfigDict(from_attributes=True)


class AssemblyRead(BaseModel):
    id: int
    name: str | None = None
    note: str | None = None
    user: UserBrief | None = None
    created_at: datetime
    cuts: list[CutRead]
    goods: list[AssemblyGoods]

    @field_serializer("created_at")
    def created_at_as_utc(self, value: datetime) -> str:
        # The database keeps UTC without an offset; state it for the browser
        return value.replace(tzinfo=timezone.utc).isoformat()

    @classmethod
    def of(cls, assembly) -> "AssemblyRead":
        return cls(
            id=assembly.id,
            name=assembly.name,
            note=assembly.note,
            user=UserBrief.model_validate(assembly.user) if assembly.user else None,
            created_at=assembly.created_at,
            cuts=[CutRead.model_validate(cut) for cut in assembly.cuts],
            goods=[
                AssemblyGoods(product=ProductRead.model_validate(m.product), quantity=-m.quantity_changed)
                for m in assembly.movements
            ],
        )
